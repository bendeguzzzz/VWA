pub fn stumpff(mut z: f64, n: u8) -> f64 {
    let mut n_counter = 0;
    while z > 0.1 {
        z /= 4.0;
        n_counter += 1;
    }

    let mut c_4 = INVERSE_FACTORIALS[4] - z * INVERSE_FACTORIALS[6];
    let mut c_5 = INVERSE_FACTORIALS[5] - z * INVERSE_FACTORIALS[7];
    let z_bar = -z;
    let mut p = z_bar;
    let mut k = 8;

    loop {
        let c_4_prev = c_4;
        p = p * z_bar;
        c_4 = c_4 + p * INVERSE_FACTORIALS[k];
        k += 1;
        c_5 = c_5 + p * INVERSE_FACTORIALS[k];
        k += 1;

        // Safety check to prevent array overflow
        if k >= INVERSE_FACTORIALS.len() || c_4 == c_4_prev {
            break;
        }
    }

    let mut c_3 = 1.0 / 6.0 - z * c_5;
    let mut c_2 = 1.0 / 2.0 - z * c_4;
    let mut c_1 = 1.0 - z * c_3;

    while n_counter > 0 {
        z = 4.0 * z;
        c_5 = 1.0 / 16.0 * (c_5 + c_4 + c_3 + c_2);
        c_4 = 1.0 / 8.0 * c_3 * (1.0 - c_1);
        c_3 = 1.0 / 6.0 - z * c_5;
        c_2 = 1.0 / 2.0 - z * c_4;
        c_1 = 1.0 - z * c_3;
        n_counter -= 1;
    }

    let c_0 = 1.0 - z * c_2;

    match n {
        0 => c_0,
        1 => c_1,
        2 => c_2,
        3 => c_3,
        4 => c_4,
        5 => c_5,
        _ => panic!("Invalid Stumpff index: {}", n),
    }
}
